-- 1. Create application user
-- Replace this example password before deployment.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_roles WHERE rolname = 'app_user'
    ) THEN
        CREATE ROLE app_user LOGIN PASSWORD 'ChangeThis_StrongPassword';
    END IF;
END
$$;

-- 2. Grant database access
GRANT CONNECT ON DATABASE company_db TO app_user;
GRANT USAGE, CREATE ON SCHEMA public TO app_user;

-- 3. Create role table
CREATE TABLE IF NOT EXISTS public.role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(255)
);

-- 4. Create services table
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(255)
);

-- 5. Create project table
CREATE TABLE IF NOT EXISTS public.project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_time TIMESTAMP(6) WITHOUT TIME ZONE,
    name VARCHAR(255)
);

-- 6. Create users table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact BIGINT,
    email VARCHAR(255),
    name VARCHAR(255),
    password VARCHAR(255),
    role_id BIGINT,
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id)
        REFERENCES public.role(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

-- 7. Create project_users mapping table
CREATE TABLE IF NOT EXISTS public.project_users (
    project_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_project_users_project
        FOREIGN KEY (project_id)
        REFERENCES public.project(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT fk_project_users_user
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

-- 8. Create role_service_mapping table
CREATE TABLE IF NOT EXISTS public.role_service_mapping (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    CONSTRAINT fk_role_service_role
        FOREIGN KEY (role_id)
        REFERENCES public.role(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT fk_role_service_service
        FOREIGN KEY (service_id)
        REFERENCES public.services(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

-- 9. Create task table
CREATE TABLE IF NOT EXISTS public.task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_time TIMESTAMP(6) WITHOUT TIME ZONE,
    name VARCHAR(255),
    status VARCHAR(255),
    project_id BIGINT NOT NULL,
    CONSTRAINT fk_task_project
        FOREIGN KEY (project_id)
        REFERENCES public.project(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);

-- 10. Create tasks_users mapping table
CREATE TABLE IF NOT EXISTS public.tasks_users (
    task_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_tasks_users_task
        FOREIGN KEY (task_id)
        REFERENCES public.task(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION,
    CONSTRAINT fk_tasks_users_user
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON UPDATE NO ACTION
        ON DELETE NO ACTION
);
